from crewai.flow.flow import Flow, start, listen
from crewai import Agent
from pydantic import BaseModel, Field
from dotenv import load_dotenv


load_dotenv()  # Load environment variables from .env file

class CityNameModel(BaseModel):
    city_name: str = Field(..., description="Name of the city generated by the agent")
    country_name: str = Field(..., description="Name of the country where city is located")

class MyAgentFlow(Flow):

    # define the start_node/trigger_node
    @start()
    def generate_city_name(self) -> dict[str, str]:
        city_agent = Agent(
            role="Expert in city names and country names in world", 
            goal="Generate a real world city name and its corresponding name of country", 
            backstory="Expert in geography and world map and you know a lot about cities in the world and the country where the city belongs."
        )

        prompt = "Generate a real world city name and its corresponding country name as well" 

        agent_op = city_agent.kickoff(messages=prompt,
                                      response_format=CityNameModel) 

        city_data = agent_op.pydantic
        print(city_data.model_dump())

        return city_data.model_dump()

    @listen(generate_city_name)
    def generate_fact(self, node_output) -> str:
        city_name = node_output["city_name"] 
        country_name = node_output["country_name"] 

        fact_agent = Agent(
            role="Expert in fun fact generation for cities around the world",
            goal=f"Generate a fun fact about the {city_name} and {country_name}",
            backstory=f"You are expert in fun fact about {city_name} and {country_name}" 
        )

        prompt = f"Generate a fun fact about the city {city_name} and country {country_name} and it must be fun to read" 

        fact = fact_agent.kickoff(messages=prompt) 
        return fact.raw

if __name__ == "__main__":
    flow = MyAgentFlow()
    res = flow.kickoff()  # start the flow
    flow.plot()  # visualize the flow
    print(res)  # prints the final output of the flow